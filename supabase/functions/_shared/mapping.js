// Converts database rows (snake_case) to the shapes the app uses (camelCase).

export const fromDb = {
  settings: (r) => ({
    maxConcurrent: r.max_concurrent,
    bookingWindowDays: r.booking_window_days,
    cutoffMinutes: r.cutoff_minutes,
    slotStep: r.slot_step,
    publicEmail: r.public_email,
    phone: r.phone,
    banner: r.banner,
  }),
  service: (r) => ({
    id: r.id,
    name: r.name,
    duration: r.duration_min,
    priceCents: r.price_cents,
    description: r.description,
    sort: r.sort,
    active: r.active,
  }),
  barber: (r) => ({ id: r.id, name: r.name, removed: r.removed, sort: r.sort }),
  weeklyHours: (r) => ({ dow: r.dow, closed: r.closed, openMin: r.open_min, closeMin: r.close_min }),
  specialDay: (r) => ({ date: r.date, closed: r.closed, openMin: r.open_min, closeMin: r.close_min, note: r.note }),
  unavailability: (r) => ({ id: r.id, barberId: r.barber_id, startDate: r.start_date, endDate: r.end_date, reason: r.reason }),
  break: (r) => ({
    id: r.id,
    barberId: r.barber_id,
    startDate: r.start_date,
    startMin: r.start_min,
    endMin: r.end_min,
    repeat: r.repeat,
    repeatDays: r.repeat_days || [],
    repeatUntil: r.repeat_until,
    label: r.label,
  }),
  busy: (r) => ({ barberId: r.barber_id, date: r.booking_date, startMin: r.start_min, endMin: r.end_min }),
  booking: (r) => ({
    id: r.id,
    groupId: r.group_id,
    barberId: r.barber_id,
    serviceId: r.service_id,
    serviceName: r.service_name,
    date: r.booking_date,
    startMin: r.start_min,
    endMin: r.end_min,
    customerName: r.customer_name,
    phone: r.phone,
    email: r.email,
    guestName: r.guest_name,
    source: r.source,
    status: r.status,
    cancelReason: r.cancel_reason,
    cancelledBy: r.cancelled_by,
    notes: r.notes,
    cancelToken: r.cancel_token,
    noShow: !!r.no_show,
    createdAt: r.created_at,
  }),
};

export const toDb = {
  settings: (s) => ({
    max_concurrent: s.maxConcurrent || null,
    booking_window_days: s.bookingWindowDays,
    cutoff_minutes: s.cutoffMinutes,
    slot_step: s.slotStep,
    public_email: s.publicEmail,
    phone: s.phone,
    banner: s.banner || null,
  }),
  service: (s) => ({
    name: s.name,
    duration_min: s.duration,
    price_cents: s.priceCents,
    description: s.description || null,
    sort: s.sort ?? 0,
    active: s.active,
  }),
  weeklyHours: (w) => ({ dow: w.dow, closed: w.closed, open_min: w.openMin, close_min: w.closeMin }),
  specialDay: (d) => ({ date: d.date, closed: d.closed, open_min: d.openMin, close_min: d.closeMin, note: d.note || null }),
  unavailability: (u) => ({ barber_id: u.barberId, start_date: u.startDate, end_date: u.endDate || null, reason: u.reason || null }),
  break: (b) => ({
    barber_id: b.barberId,
    start_date: b.startDate,
    start_min: b.startMin,
    end_min: b.endMin,
    repeat: b.repeat,
    repeat_days: b.repeatDays || [],
    repeat_until: b.repeat === 'none' ? null : b.repeatUntil || null,
    label: b.label || null,
  }),
  booking: (b) => ({
    barber_id: b.barberId,
    service_id: b.serviceId,
    service_name: b.serviceName,
    booking_date: b.date,
    start_min: b.startMin,
    end_min: b.endMin,
    customer_name: b.customerName,
    phone: b.phone || null,
    email: b.email || null,
    guest_name: b.guestName || null,
    notes: b.notes || null,
  }),
};

export function assembleData({ settings, services, barbers, weeklyHours, specialDays, unavailability, breaks }) {
  return {
    settings: fromDb.settings(settings),
    services: services.map(fromDb.service).sort((a, b) => a.sort - b.sort),
    barbers: barbers.map(fromDb.barber).sort((a, b) => a.sort - b.sort || a.name.localeCompare(b.name)),
    weeklyHours: weeklyHours.map(fromDb.weeklyHours),
    specialDays: specialDays.map(fromDb.specialDay),
    unavailability: unavailability.map(fromDb.unavailability),
    breaks: breaks.map(fromDb.break),
  };
}
